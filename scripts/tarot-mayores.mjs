const PELO = "#7a4b25";
const GRIS = "#9aa3a8";

/** Túnica trapezoidal con dobladillo. */
const tunica = (x, y, wa, wb, h, fill) => P(`M${x - wa} ${y} L${x + wa} ${y} L${x + wb} ${y + h} L${x - wb} ${y + h} Z`, fill);
/** Pliegues de tela. */
const pliegues = (x, y, h, n = 3, sep = 40) => Array.from({ length: n }, (_, i) => L(x + (i - (n - 1) / 2) * sep, y, x + (i - (n - 1) / 2) * sep * 1.35, y + h, 4)).join("");
/** Barba. */
const barba = (x, y, w = 46) => P(`M${x - w} ${y - 10} Q${x - w} ${y + w * 1.7} ${x} ${y + w * 1.9} Q${x + w} ${y + w * 1.7} ${x + w} ${y - 10} Q${x} ${y + 24} ${x - w} ${y - 10} Z`, MARFIL, 6);
const mano = (x, y, r = 20) => C(x, y, r, CARNE, 6);
const alas = (x, y, w, h, fill = MARFIL) => {
  const lado = s => P(`M${x + s * 40} ${y} Q${x + s * w} ${y - h * 0.9} ${x + s * (w + 40)} ${y - h * 0.5} Q${x + s * (w + 20)} ${y - h * 0.1} ${x + s * (w - 20)} ${y + h * 0.15} Q${x + s * (w - 40)} ${y + h * 0.5} ${x + s * 70} ${y + h * 0.7} Z`, fill, 7);
  return lado(-1) + lado(1);
};
const nubes = (y, ancho = 300) => [
  P(`M${-ancho} ${y} q0 -50 70 -50 q10 -60 100 -50 q70 -50 130 20 q70 -10 70 80 Z`, MARFIL, 7),
  P(`M${-ancho + 80} ${y + 60} q0 -40 60 -40 q60 -10 90 30 q60 -30 100 20 q50 -20 90 -20 q40 0 50 40 Z`, MARFIL2, 7)
].join("");
const halo = (x, y, r) => C(x, y, r, "none", 7) + C(x, y, r - 14, "none", 3);
const ladrillos = (x, y, w, h, fill) => {
  let s = P(`M${x} ${y} h${w} v${h} h${-w} Z`, fill);
  for (let i = 1; i < h / 40; i++) s += L(x, y + i * 40, x + w, y + i * 40, 4);
  for (let f = 0; f < h / 40; f++) for (let j = 1; j < w / 60; j++) s += L(x + j * 60 + (f % 2 ? 30 : 0), y + f * 40, x + j * 60 + (f % 2 ? 30 : 0), y + f * 40 + 40, 4);
  return s;
};

